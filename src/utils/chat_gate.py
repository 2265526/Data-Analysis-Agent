"""闲聊检测与回复(入口拦截): 避免闲聊被当作数据分析任务提交进流水线。

设计:
- 规则引擎(零 LLM 成本): 问候/寒暄/致谢/告别/自我介绍等闲聊词 + 分析特征词
  双端判断 —— 命中闲聊词且不含分析特征词才判定为闲聊, 避免误伤
  ("统计一下销售额, 谢谢你" 含分析词 -> 走正常流水线)
- 前端(Index.vue)与后端(submit_task)共用同一套规则: 前端即时回复, 后端兜底拦截
- 回复引导用户回到数据分析场景
"""
from __future__ import annotations

import random

# 闲聊触发词
_CHITCHAT_WORDS = [
    "你好", "您好", "嗨", "哈喽", "hello", "hi", "hey", "早上好", "下午好", "晚上好",
    "在吗", "在不在", "谢谢", "感谢", "辛苦了", "多谢", "thank", "thanks",
    "再见", "拜拜", "晚安", "bye", "告辞", "886",
    "你是谁", "你叫什么", "你能做什么", "你会做什么", "介绍一下", "介绍下你", "有什么功能",
    "哈哈", "嗯嗯", "好的", "好呀", "ok", "okk", "在干嘛", "吃饭了吗", "天气", "心情",
    "无聊", "开心", "真棒", "不错", "厉害", "加油", "嗯", "哦", "好的吧",
]
# 分析特征词: 命中任一即视为数据分析需求(优先级高于闲聊词)
_ANALYSIS_HINTS = [
    "统计", "销售额", "查询", "数据", "报表", "对比", "趋势", "占比", "分析", "明细",
    "订单", "品类", "用户", "留存", "转化", "环比", "同比", "最近", "近7", "近30",
    "上周", "本月", "sql", "数据库", "销量", "金额", "多少", "几个", "几号", "增长率",
    "客单价", "库存", "毛利", "图表", "报告", "看板", "下钻", "求和", "均值",
]


def is_chitchat(text: str | None) -> bool:
    """判断输入是否为闲聊(非数据分析需求)。"""
    t = (text or "").strip().lower()
    if not t:
        return True
    # 含分析特征词 -> 视为分析需求(即使带问候语)
    if any(h in t for h in _ANALYSIS_HINTS):
        return False
    # 长度极短且无分析词 -> 大概率闲聊(如 "嗯" / "好" / "?" )
    if len(t) < 2:
        return True
    return any(w in t for w in _CHITCHAT_WORDS)


_CHAT_REPLIES = [
    "你好呀！我是数据分析助手 🤖\n\n我只擅长数据分析, 例如:\n- 统计最近7天各品类销售额, 对比上周变化\n- 分析近30天销售趋势\n- 查询各品类订单量与客单价\n\n请直接输入你的业务问题, 我来帮你分析～",
    "嗨！😄 我是专门做数据分析的助手。\n\n你可以问我类似这样的问题:\n- 最近7天各品类销售额是多少\n- 各品类销售额环比变化\n- 近30天销售趋势如何\n\n期待你的业务问题～",
    "你好！这里是数据分析助手 🤖\n\n我不能闲聊, 但可以帮你:\n- 统计销售额/订单量/客单价\n- 分析品类结构与趋势\n- 对比上周/上月/去年同期\n\n请直接告诉我你想分析什么吧！",
]


def chat_reply(query: str | None = None) -> str:
    """生成闲聊回复(固定文案轮换, 引导回数据分析)。"""
    return random.choice(_CHAT_REPLIES)
